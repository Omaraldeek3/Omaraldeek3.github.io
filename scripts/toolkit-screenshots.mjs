import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
await mkdir('docs/toolkit-screenshots',{recursive:true});
await page.goto('http://localhost:3012/tools');
await page.getByRole('button',{name:'Arrange parts',exact:true}).click();
await page.getByText('Layout ready',{exact:true}).waitFor();
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'docs/toolkit-screenshots/nesting-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Image to vector',exact:true}).click();
await page.getByRole('button',{name:'Trace image',exact:true}).click();
await page.getByText('Vector ready',{exact:true}).waitFor();
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'docs/toolkit-screenshots/tracing-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'العربية',exact:true}).click();
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'docs/toolkit-screenshots/tracing-arabic-mobile.png',fullPage:true});
await browser.close();
console.log('Saved desktop nesting, desktop tracing and Arabic mobile screenshots.');
